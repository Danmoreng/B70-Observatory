export type StudioMessage = keyof typeof studioGerman;
export function studioText(
  message: StudioMessage,
  values?: Record<string, string | number>
): string {
  const text = locale.value === 'de' ? studioGerman[message] : message;
  return values
    ? text.replace(/\{(\w+)\}/g, (match, key: string) =>
        values[key] === undefined ? match : String(values[key])
      )
    : text;
}
/** Known engine phases, statuses and built-in collection names. Authored content stays intact. */
export function studioLabel(value: string): string {
  return Object.prototype.hasOwnProperty.call(studioGerman, value)
    ? studioText(value as StudioMessage)
    : value;
}
